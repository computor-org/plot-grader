#!/usr/bin/env python3
"""Round-4 report: strict vs tolerant judging, scored against visual labels.

Usage: report_round4.py RESULTS_DIR MANIFEST VISUAL_LABELS OUT.md

The truth is the visual label per case (docs/criteria.md), not the official
tests. The tests, Tier 1, a pixel comparison and the model verdicts are all
scored against it.
"""

import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
from PIL import Image

from plot_grader.tolerant import tolerant_check, unseeded_random

EXAMPLES = Path.home() / "code/codeability/examples/python"

STAGES = [("r4_strict", "strict prompt (round 3)"),
          ("r4_tolerant", "tolerant prompt"),
          ("r4_tolerant_rep", "tolerant prompt, repeat"),
          ("r4_jev_tolerant", "JEV, tolerant question only")]
PIXEL_THRESHOLDS = (0.0, 0.002, 0.01, 0.03)


def pixel_diff(a: str, b: str) -> float | None:
    """Share of pixels that differ visibly; None if the image sizes differ."""
    A = np.asarray(Image.open(a).convert("L"), float)
    B = np.asarray(Image.open(b).convert("L"), float)
    return float((np.abs(A - B) > 10).mean()) if A.shape == B.shape else None


def score(pairs: list) -> dict:
    """pairs: (truth, verdict) with verdict PASS, FAIL or None."""
    done = [(t, v) for t, v in pairs if v]
    return {"n": len(pairs),
            "acc": sum(t == v for t, v in done) / len(done) if done else None,
            "false_pass": sum(t == "FAIL" and v == "PASS" for t, v in done),
            "false_fail": sum(t == "PASS" and v == "FAIL" for t, v in done),
            "unusable": len(pairs) - len(done)}


def fmt(v, spec=".2f"):
    return "-" if v is None else format(v, spec)


def score_row(name: str, s: dict, extra: str = "") -> str:
    return (f"| {name} | {fmt(s['acc'])} | {s['false_pass']} | {s['false_fail']} "
            f"| {s['unusable']} |{extra}")


def main():
    res, manifest, labels_path, out_md = map(Path, sys.argv[1:5])
    cases = {r["id"]: r for r in map(json.loads, open(manifest)) if "png" in r
             and r.get("label")}
    visual = {r["id"]: r for r in map(json.loads, open(labels_path))}
    cases = {i: c for i, c in cases.items() if i in visual}
    for i, c in cases.items():
        c["visual"] = visual[i]["visual"]
        c["kind"] = (c["source"].split("/", 1)[1] if c["source"].startswith("mutation/")
                     else "solution")
        c["pixel"] = pixel_diff(c["png"], c["reference_png"])
        ref_src = EXAMPLES / f"itpcp.pgph.py.{c['slug']}" / c["entry"]
        c["checks"] = tolerant_check(*(json.loads(Path(p).with_suffix(".json").read_text())
                                       ["plot_data"] for p in (c["png"], c["reference_png"])),
                                     random_data=ref_src.exists()
                                     and unseeded_random(ref_src.read_text()))

    stages = {}
    for key, _ in STAGES:
        f = res / key / "rows.jsonl"
        if f.exists():
            rows = [json.loads(line) for line in open(f)]
            stages[key] = {r["case"]: r for r in rows if r["case"] in cases}
            summ = json.loads((res / key / "summary.json").read_text())["cells"][0]
            lat = sorted(r["latency_s"] for r in rows if not r["error"])
            stages[key + "@"] = {"thr": summ.get("throughput_per_min"),
                                 "p50": statistics.median(lat) if lat else None}
    tier1 = {}
    for rows in (s for k, s in stages.items() if not k.endswith("@")):
        tier1.update({i: r["tier1"] for i, r in rows.items()})

    n_pass = sum(c["visual"] == "PASS" for c in cases.values())
    lines = ["# Round 4: tolerant vs strict judging (Flash-Next)", "",
             "Generated by `scripts/report_round4.py` from `scripts/run_round4.sh`.",
             "Truth is the visual label of each case against `docs/criteria.md`",
             "(same content passes, style and wording may differ), labelled blind by",
             "eye from side-by-side sheets (`scripts/make_label_sheets.py`). The",
             "official tests are scored against the same labels.", "",
             f"{len(cases)} cases, {n_pass} visually acceptable, "
             f"{len(cases) - n_pass} not. Flash-Next (self-hosted), images at 75 %, "
             "16 parallel requests (JEV 8).", ""]

    # 1. Deciders against the visual truth.
    head = ["| decider | acc vs visual | false passes | false fails | unusable |",
            "|---|---|---|---|---|"]
    lines += ["## 1. Who decides best", ""] + head
    lines.append(score_row("official tests", score([(c["visual"], c["label"])
                                                     for c in cases.values()])))
    lines.append(score_row("Tier 1 (data)", score([(c["visual"], tier1.get(i))
                                                    for i, c in cases.items()])))
    for key, name in STAGES:
        if key in stages:
            s = score([(c["visual"], stages[key].get(i, {}).get("verdict"))
                       for i, c in cases.items()])
            lines.append(score_row(name, s))
    tol = stages.get("r4_tolerant", {})
    if tol:
        def policy(fn):
            return score([(c["visual"], fn(i, c)) for i, c in cases.items()])
        tv = {i: r["verdict"] for i, r in tol.items()}
        lines.append(score_row("pixel-identical → PASS, else tolerant model",
                               policy(lambda i, c: "PASS" if c["pixel"] == 0 else tv.get(i))))
        lines.append(score_row("tolerant data checks (`tolerant.py`) only",
                               policy(lambda i, c: "FAIL" if c["checks"] else "PASS")))
        lines.append(score_row("**tolerant model and tolerant data checks both PASS**",
                               policy(lambda i, c: "FAIL" if c["checks"] else tv.get(i))))
        lines.append(score_row("tests PASS or tolerant model PASS",
                               policy(lambda i, c: "PASS" if "PASS" in (c["label"], tv.get(i))
                                      else tv.get(i) or c["label"])))
        lines.append(score_row("Tier 1 PASS or tolerant model PASS",
                               policy(lambda i, c: "PASS" if "PASS" in (tier1.get(i), tv.get(i))
                                      else tv.get(i) or tier1.get(i))))

    # 2. Rescues and misses of the tests.
    if tol:
        lines += ["", "## 2. Where the tests are wrong", ""]
        too_strict = [i for i, c in cases.items() if c["label"] == "FAIL" and c["visual"] == "PASS"]
        too_lax = [i for i, c in cases.items() if c["label"] == "PASS" and c["visual"] == "FAIL"]
        lines += [f"- Tests FAIL a visually acceptable plot: {len(too_strict)} cases. "
                  f"The tolerant model passes {sum(tv.get(i) == 'PASS' for i in too_strict)}, "
                  f"the strict model {sum(stages.get('r4_strict', {}).get(i, {}).get('verdict') == 'PASS' for i in too_strict)}.",
                  f"- Tests PASS a visually wrong plot: {len(too_lax)} cases. "
                  f"The tolerant model fails {sum(tv.get(i) == 'FAIL' for i in too_lax)}."]

    # 3. Per kind of change.
    lines += ["", "## 3. Share judged PASS per kind of change", "",
              "| kind | cases | visually OK | tests | Tier 1 | strict | tolerant | JEV tolerant |",
              "|---|---|---|---|---|---|---|---|"]
    by_kind = defaultdict(list)
    for i, c in cases.items():
        by_kind[c["kind"]].append(i)

    def share(ids, get):
        vals = [get(i) for i in ids]
        vals = [v for v in vals if v]
        return f"{sum(v == 'PASS' for v in vals)}/{len(vals)}" if vals else "-"
    for kind in sorted(by_kind, key=lambda k: (k != "solution", k)):
        ids = by_kind[kind]
        lines.append(
            f"| {kind} | {len(ids)} | {share(ids, lambda i: cases[i]['visual'])} "
            f"| {share(ids, lambda i: cases[i]['label'])} | {share(ids, tier1.get)} "
            f"| {share(ids, lambda i: stages.get('r4_strict', {}).get(i, {}).get('verdict'))} "
            f"| {share(ids, lambda i: tol.get(i, {}).get('verdict'))} "
            f"| {share(ids, lambda i: stages.get('r4_jev_tolerant', {}).get(i, {}).get('verdict'))} |")

    # 4. Pixel comparison.
    lines += ["", "## 4. Pixel comparison as a first gate", "",
              "Share of visibly differing pixels between student and reference image",
              "(same image size only).", "",
              "| differing pixels ≤ | cases | visually OK | visually wrong |", "|---|---|---|---|"]
    for t in PIXEL_THRESHOLDS:
        ids = [i for i, c in cases.items() if c["pixel"] is not None and c["pixel"] <= t]
        ok = sum(cases[i]["visual"] == "PASS" for i in ids)
        lines.append(f"| {t:.1%} | {len(ids)} | {ok} | {len(ids) - ok} |")

    # 5. Stability, speed, misses.
    lines += ["", "## 5. Stability and speed", ""]
    rep = stages.get("r4_tolerant_rep", {})
    if tol and rep:
        same = sum(tol[i]["verdict"] == rep[i]["verdict"] for i in tol if i in rep)
        lines.append(f"- Tolerant prompt, two runs: {same}/{len(tol)} cases got the same verdict.")
    for key, name in STAGES:
        if key + "@" in stages:
            st = stages[key + "@"]
            lines.append(f"- {name}: {fmt(st['thr'], '.1f')} calls/min, "
                         f"median {fmt(st['p50'], '.1f')} s per call.")
    if tol:
        lines += ["", "## 6. Tolerant model errors", "",
                  "| case kind | visual | model | criterion (label) | model's differences |",
                  "|---|---|---|---|---|"]
        for i, c in sorted(cases.items(), key=lambda x: x[1]["kind"]):
            r = tol.get(i)
            if r and r["verdict"] and r["verdict"] != c["visual"]:
                diff = "; ".join(r["differences"])[:160].replace("|", "/")
                lines.append(f"| {c['kind']} | {c['visual']} | {r['verdict']} "
                             f"| {visual[i].get('criterion', '')} | {diff} |")
    out_md.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_md}")


if __name__ == "__main__":
    main()
